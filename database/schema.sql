-- Name: v_order_finance; Type: VIEW; Schema: pizzeria; Owner: -
--

CREATE VIEW pizzeria.v_order_finance AS
 SELECT o.id AS order_id,
    sum(((oi.quantity)::numeric * oi.price_at_order)) AS items_total,
    o.discount_id,
    d.type AS discount_type,
    d.value AS discount_value,
        CASE
            WHEN (d.type = 'промокод'::pizzeria.discount_type) THEN round((sum(((oi.quantity)::numeric * oi.price_at_order)) * (d.value / 100.0)), 2)
            WHEN (d.type = 'накопительная'::pizzeria.discount_type) THEN COALESCE(d.value, (0)::numeric)
            ELSE (0)::numeric
        END AS discount_amount,
    round((sum(((oi.quantity)::numeric * oi.price_at_order)) -
        CASE
            WHEN (d.type = 'промокод'::pizzeria.discount_type) THEN (sum(((oi.quantity)::numeric * oi.price_at_order)) * (d.value / 100.0))
            WHEN (d.type = 'накопительная'::pizzeria.discount_type) THEN COALESCE(d.value, (0)::numeric)
            ELSE (0)::numeric
        END), 2) AS total_after_discount
   FROM ((pizzeria.orders o
     JOIN pizzeria.order_items oi ON ((oi.order_id = o.id)))
     LEFT JOIN pizzeria.discounts d ON ((d.id = o.discount_id)))
  GROUP BY o.id, o.discount_id, d.type, d.value;


